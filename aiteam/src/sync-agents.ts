/**
 * Persona → native subagent binding (ADR 0001, migration sketch step 2).
 *
 * `aiteam/agents/*.md` stays canonical and engine-neutral — Antigravity, Gemini
 * and Cursor keep reading the prose. `.claude/agents/*.md` is the Claude Code
 * *binding* of the same intent, generated from it, never a second source of
 * truth. Same shape as the tiers→hooks reference implementation: canonical
 * config + tested logic + harness wiring.
 */

/** Same enum as `impl_model` in `.beads/SCHEMA.md` — the model policy is one policy. */
const MODELS = ["sonnet", "opus", "haiku"] as const;
export type Model = (typeof MODELS)[number];

export interface Persona {
  /** Native subagent name. Derived from the filename so it can never drift from a second field. */
  slug: string;
  /** Human form, kept for the prose layer ("SRE / FinOps"). */
  name: string;
  description: string;
  model: Model;
  /** False for the session persona (the orchestrator dispatches; it is not dispatched). */
  dispatchable: boolean;
  body: string;
}

export const GENERATED_MARKER =
  "<!-- GENERATED by aiteam/scripts/sync-agents.ts — do not edit here.\n" +
  "     Edit the canonical persona, then run: npm --prefix aiteam run sync:agents\n" +
  "     Source: aiteam/agents/{SOURCE} -->";

const marker = (source: string): string => GENERATED_MARKER.replace("{SOURCE}", source);

export function isGenerated(content: string): boolean {
  return content.includes("GENERATED by aiteam/scripts/sync-agents.ts");
}

/**
 * Parse a canonical persona file. Throws with the filename in the message —
 * a sync that fails silently on one persona leaves a hole in the roster that
 * nobody notices until a dispatch picks the wrong agent.
 */
export function parsePersona(raw: string, filename: string): Persona {
  const slug = filename.replace(/\.md$/, "");
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(raw);
  if (!match) {
    throw new Error(`${filename}: sem frontmatter — o binding nativo exige name, description e model.`);
  }

  const fields = new Map<string, string>();
  for (const line of (match[1] ?? "").split(/\r?\n/)) {
    const kv = /^([a-z_]+):\s*(.+?)\s*$/.exec(line);
    if (kv?.[1] && kv[2]) fields.set(kv[1], kv[2]);
  }

  const name = fields.get("name");
  const description = fields.get("description");
  const model = fields.get("model");

  if (!name) throw new Error(`${filename}: frontmatter sem 'name'.`);
  if (!description) {
    throw new Error(
      `${filename}: frontmatter sem 'description' — é o campo que o dispatcher nativo usa para escolher a persona sozinho.`,
    );
  }
  // O binding gerado é YAML de verdade para o harness: um ": " num escalar
  // plano vira mapping aninhado e derruba o arquivo inteiro em runtime, longe
  // deste parser. Barrar aqui é mais barato que descobrir lá.
  if (description.includes(": ")) {
    throw new Error(
      `${filename}: 'description' não pode conter dois-pontos seguidos de espaço — o YAML do binding gerado leria como mapping. Use travessão ou vírgula.`,
    );
  }
  if (!model || !MODELS.includes(model as Model)) {
    throw new Error(`${filename}: 'model' deve ser um de ${MODELS.join(" | ")} (recebi: ${model ?? "nada"}).`);
  }

  return {
    slug,
    name,
    description,
    model: model as Model,
    dispatchable: fields.get("dispatch") !== "session",
    // `.md` fica fora do eol=lf do .gitattributes: a persona chega CRLF num
    // checkout Windows e LF num Linux. Sem isso, a mesma fonte gera bindings
    // diferentes por plataforma e o drift check acusa divergência fantasma.
    body: raw.slice(match[0].length).replace(/\r\n/g, "\n").trim(),
  };
}

export function renderBinding(persona: Persona): string {
  return [
    "---",
    `name: ${persona.slug}`,
    `description: ${persona.description}`,
    `model: ${persona.model}`,
    "---",
    "",
    marker(`${persona.slug}.md`),
    "",
    persona.body,
    "",
  ].join("\n");
}

export type SyncAction = "create" | "update" | "up-to-date" | "host-owned" | "orphan";

export interface SyncPlanEntry {
  slug: string;
  action: SyncAction;
  /** Content to write. Absent for actions that must not touch the file. */
  content?: string;
}

/**
 * Decide what to do per binding, without touching disk.
 *
 * `host-owned` is the non-interference invariant from the vendoring runbook:
 * a consumer may ship its own `.claude/agents/backend-architect.md`, and the
 * framework overwriting it would be exactly the clobber that `install.mjs`
 * refuses to do to `settings.json`. We report and step aside.
 */
export function planSync(personas: Persona[], existing: Map<string, string>): SyncPlanEntry[] {
  const plan: SyncPlanEntry[] = [];
  const known = new Set<string>();

  for (const persona of personas) {
    if (!persona.dispatchable) continue;
    known.add(persona.slug);

    const current = existing.get(persona.slug);
    const content = renderBinding(persona);

    if (current === undefined) plan.push({ slug: persona.slug, action: "create", content });
    else if (!isGenerated(current)) plan.push({ slug: persona.slug, action: "host-owned" });
    else if (current === content) plan.push({ slug: persona.slug, action: "up-to-date" });
    else plan.push({ slug: persona.slug, action: "update", content });
  }

  // Bindings gerados cuja persona sumiu viram subagente fantasma: continuam
  // despacháveis pelo harness sem fonte canônica por trás.
  for (const [slug, content] of existing) {
    if (known.has(slug)) continue;
    plan.push({ slug, action: isGenerated(content) ? "orphan" : "host-owned" });
  }

  return plan;
}

/** Actions that mean the checked-in bindings no longer match the personas. */
export function isDrift(action: SyncAction): boolean {
  return action === "create" || action === "update" || action === "orphan";
}
